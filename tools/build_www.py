#!/usr/bin/env python3
"""把 webui/index.html gzip 成 firmware/main/www.h（固件里内嵌，无需外网 CDN）。"""
import gzip
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "webui", "index.html")
DST = os.path.join(ROOT, "firmware", "main", "www.h")


def main():
    raw = open(SRC, "rb").read()
    gz = gzip.compress(raw, 9)
    with open(DST, "w", encoding="utf-8") as f:
        f.write("/* generated by tools/build_www.py - do not edit */\n")
        f.write("#pragma once\n\n")
        f.write(f"/* index.html {len(raw)} bytes -> gzip {len(gz)} bytes */\n")
        f.write("static const unsigned char www_gz[] = {\n")
        for i in range(0, len(gz), 20):
            f.write("    " + ",".join(str(b) for b in gz[i:i + 20]) + ",\n")
        f.write("};\n")
        f.write(f"static const unsigned int www_gz_len = {len(gz)};\n")
    print(f"{SRC}: {len(raw)} -> {len(gz)} bytes gzip")


if __name__ == "__main__":
    main()
